// Cell value 10 = indestructible
export function isIndestructible(cell) { return cell === 10; }

function cellToColor(cell) {
  if (cell === 0) return null;
  if (cell === 10) return INDESTRUCTIBLE_COLOR;
  const idx = Math.min(cell - 1, BRICK_COLORS.length - 1);
  return BRICK_COLORS[idx];
}

export function createLevel(level) {
  // Boss level: special layout
  if (isBossLevel(level)) {
    return createBossLevel(level);
  }

  // Cycle through levels (1-indexed), repeat after LEVEL_MAPS.length
  const mapIdx = ((level - 1) % LEVEL_MAPS.length);
  const map = LEVEL_MAPS[mapIdx];
  const bricks = [];

  for (let r = 0; r < map.length; r++) {
    for (let c = 0; c < map[r].length; c++) {
      const cell = map[r][c];
      if (cell === 0) continue;
      const colorData = cellToColor(cell);
      if (!colorData) continue;

      // Scale up hits for later cycles
      const cycleBonus = Math.floor((level - 1) / LEVEL_MAPS.length);
      const hits = colorData.hits + cycleBonus;

      const indestructible = isIndestructible(cell);
      const diff = getDiffSettings();
      const isExplosive = !indestructible && Math.random() < diff.explosiveChance;
      bricks.push({
        x: BRICK.offsetLeft + c * (BRICK.width + BRICK.padding),
        y: BRICK.offsetTop + r * (BRICK.height + BRICK.padding),
        width: BRICK.width,
        height: BRICK.height,
        color: isExplosive ? "#ff6600" : colorData.fill,
        glow: isExplosive ? "#ff4400" : colorData.glow,
        hits: indestructible ? Infinity : hits,
        maxHits: indestructible ? Infinity : hits,
        alive: true,
        indestructible,
        explosive: isExplosive,
        hasDrop: indestructible ? false : Math.random() < diff.dropChance,
        dropType: indestructible ? null : POWERUP_POOL[Math.floor(Math.random() * POWERUP_POOL.length)],
      });
    }
  }

  return bricks;
}

export function createBossLevel(level) {
  const bossStage = Math.floor(level / 10); // 1, 2, 3...
  const bossHp = 15 + bossStage * 8;        // 23, 31, 39...
  const bricks = [];

  // Boss brick — wide, tall, centered at top
  const bossWidth = 160;
  const bossHeight = 40;
  bricks.push({
    x: CANVAS_WIDTH / 2 - bossWidth / 2,
    y: 70,
    width: bossWidth,
    height: bossHeight,
    color: "#ff0055",
    glow: "#ff0055",
    hits: bossHp,
    maxHits: bossHp,
    alive: true,
    isBoss: true,
    bossStage,
    // Movement
    moveDir: 1,
    moveSpeed: 1.2 + bossStage * 0.3,
    hasDrop: false,
    dropType: null,
    // Extra guaranteed drops (handled specially)
    bossDrops: ["WIDE_PADDLE", "EXTRA_LIFE", "MULTI_BALL"],
  });

  // Guard bricks around boss
  const GUARD_COLS = 9;
  const guardColors = [
    { fill: "#ff4488", glow: "#ff4488", hits: 2 + bossStage },
    { fill: "#cc0044", glow: "#cc0044", hits: 3 + bossStage },
  ];

  // Two rows of guard bricks
  for (let row = 0; row < 2; row++) {
    for (let c = 0; c < GUARD_COLS; c++) {
      const col = guardColors[(row + c) % 2];
      bricks.push({
        x: BRICK.offsetLeft + c * (BRICK.width + BRICK.padding),
        y: 130 + row * (BRICK.height + BRICK.padding),
        width: BRICK.width,
        height: BRICK.height,
        color: col.fill,
        glow: col.glow,
        hits: col.hits,
        maxHits: col.hits,
        alive: true,
        isBoss: false,
        hasDrop: Math.random() < 0.25,
        dropType: POWERUP_POOL[Math.floor(Math.random() * POWERUP_POOL.length)],
      });
    }
  }

  return bricks;
}

